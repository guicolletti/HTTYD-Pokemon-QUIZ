const Dragoes = {
  lista: (() => {
    const cont = {};
    DRAGOES_BRUTO.forEach(r => (cont[r[0]] = (cont[r[0]] || 0) + 1));
    return DRAGOES_BRUTO.map(([nome, pt, classe, estreia, tam, cor, cabecas, wiki, livro], i) => {
      const dup = cont[nome] > 1;
      const rotulo = (pt ? `${nome} (${pt})` : nome) + (dup && livro ? ' — livros' : dup ? ' — filmes/séries' : '');
      const w = wiki || nome;
      return {
        id: 'd' + i, tipo: 'dragao', nome, pt, rotulo, classe, estreia, tam, cor, cabecas, livro: !!livro,
        wiki: w, render: SILHUETAS_DR[w] || null, chaves: [U.chave(nome), pt ? U.chave(pt) : null].filter(Boolean),
      };
    });
  })(),
  _img: U.ler(CACHE_DR, {}),   // título da página -> imagem principal
  _rnd: U.ler(CACHE_DR + 'r', {}), // arquivo transparente -> URL

  /* imagem para mostrar (prefere a transparente) */
  imagem(d) { return (d.render && this._rnd[d.render]) || this._img[d.wiki] || null; },
  silhueta(d) { return d.render ? this._rnd[d.render] || null : null; },
  comSilhueta() { return this.lista.filter(d => this.silhueta(d)); },

  carregarImagens(aoProgresso = () => {}) {
    if (this._ouvintes) { this._ouvintes.push(aoProgresso); return this._promessa; }
    this._ouvintes = [aoProgresso];
    const avisar = p => this._ouvintes.forEach(f => f(p));
    this._promessa = this._carregar(avisar).finally(() => { this._ouvintes = null; });
    return this._promessa;
  },
  async _api(params) {
    const r = await fetch(`${WIKI_API}?action=query&format=json&origin=*&${params}`);
    return r.json();
  },
  async _carregar(aoProgresso) {
    const renders = [...new Set(this.lista.map(d => d.render).filter(f => f && !(f in this._rnd)))];
    const paginas = [...new Set(this.lista.filter(d => !(d.wiki in this._img)).map(d => d.wiki))];
    const total = renders.length + paginas.length;
    if (!total) return;
    let feitos = 0;
    for (let i = 0; i < renders.length; i += 45) {
      const lote = renders.slice(i, i + 45);
      try {
        const j = await this._api('prop=imageinfo&iiprop=url&iiurlwidth=420&titles=' + encodeURIComponent(lote.map(f => 'File:' + f).join('|')));
        const mapa = {};
        (j.query.normalized || []).forEach(n => (mapa[n.to] = n.from));
        for (const f of lote) this._rnd[f] = null;
        for (const p of Object.values(j.query.pages || {})) {
          const orig = (mapa[p.title] || p.title).replace(/^File:/, '');
          const ii = p.imageinfo && p.imageinfo[0];
          if (ii) this._rnd[orig] = ii.thumburl || ii.url;
        }
      } catch (e) { console.warn('HTTYD Wiki indisponível', e); }
      feitos += lote.length; aoProgresso(feitos / total);
    }
    for (let i = 0; i < paginas.length; i += 40) {
      const lote = paginas.slice(i, i + 40);
      try {
        const j = await this._api('redirects=1&prop=pageimages&piprop=thumbnail&pithumbsize=420&titles=' + encodeURIComponent(lote.join('|')));
        const mapa = {};
        (j.query.normalized || []).forEach(n => (mapa[n.to] = n.from));
        (j.query.redirects || []).forEach(r => (mapa[r.to] = mapa[r.from] || r.from));
        for (const t of lote) this._img[t] = null;
        for (const p of Object.values(j.query.pages || {})) {
          const orig = mapa[p.title] || p.title;
          if (p.thumbnail) this._img[orig] = p.thumbnail.source;
        }
      } catch (e) { console.warn('HTTYD Wiki indisponível', e); }
      feitos += lote.length; aoProgresso(feitos / total);
    }
    U.gravar(CACHE_DR, this._img); U.gravar(CACHE_DR + 'r', this._rnd);
  },
  limparCache() { this._img = {}; this._rnd = {}; localStorage.removeItem(CACHE_DR); localStorage.removeItem(CACHE_DR + 'r'); },
};
